/// Logging target of this module.
const TARGET: &str = "backends.llm";

#[derive(Clone)]
struct Provider {
    id: BackendId,
    name: &'static str,
    model: ModelId,
    host: &'static str,
    message_endpoint: Endpoint,
    count_endpoint: Endpoint,
    kind: ProviderKind,
}

/// `https://{host}{path}` for a compile-time provider constant.
///
/// # Panics
///
/// Panics when the constant is not an https URL: a programming bug in
/// `wire`, caught by every backend test.
fn constant_endpoint(host: &str, path: &str) -> Endpoint {
    Endpoint::parse(&format!("https://{host}{path}"))
        .expect("provider endpoint constants are https URLs")
}

impl Provider {
    fn haiku() -> Self {
        Self {
            id: BackendId::AnthropicHaiku,
            name: "haiku",
            model: BackendId::AnthropicHaiku.descriptor().default_model(),
            host: wire::ANTHROPIC_HOST,
            message_endpoint: constant_endpoint(wire::ANTHROPIC_HOST, wire::HAIKU_MESSAGE_PATH),
            count_endpoint: constant_endpoint(wire::ANTHROPIC_HOST, wire::HAIKU_COUNT_PATH),
            kind: ProviderKind::Anthropic,
        }
    }

    fn luna() -> Self {
        Self {
            id: BackendId::OpenAiLuna,
            name: "luna",
            model: BackendId::OpenAiLuna.descriptor().default_model(),
            host: wire::OPENAI_HOST,
            message_endpoint: constant_endpoint(wire::OPENAI_HOST, wire::LUNA_MESSAGE_PATH),
            count_endpoint: constant_endpoint(wire::OPENAI_HOST, wire::LUNA_COUNT_PATH),
            kind: ProviderKind::OpenAi,
        }
    }
}

struct Prepared {
    message_body: Arc<str>,
    count_body: Arc<str>,
}

#[derive(Clone)]
struct Client<T> {
    provider: Provider,
    api_key: ResolvedApiKey,
    http: HttpClient<T>,
    log: SharedGeneralLog,
    #[cfg(feature = "test-util")]
    wire_fault: Option<WireFault>,
}

impl<T: Transport> Client<T> {
    fn new(provider: Provider, api_key: ResolvedApiKey, transport: T) -> Self {
        Self {
            provider,
            api_key,
            http: HttpClient::new(transport),
            log: Arc::new(NoopGeneralLog),
            #[cfg(feature = "test-util")]
            wire_fault: None,
        }
    }

    /// The payload text embedded in the message, after any seeded fault.
    #[cfg(feature = "test-util")]
    fn embedded_text<'a>(&self, text: &'a str) -> std::borrow::Cow<'a, str> {
        match self.wire_fault {
            Some(fault) => std::borrow::Cow::Owned(fault.apply_to_text(text)),
            None => std::borrow::Cow::Borrowed(text),
        }
    }

    #[cfg(not(feature = "test-util"))]
    fn embedded_text<'a>(&self, text: &'a str) -> std::borrow::Cow<'a, str> {
        std::borrow::Cow::Borrowed(text)
    }

    /// The serialized message body after any seeded fault.
    #[cfg(feature = "test-util")]
    fn faulted_body(&self, body: String) -> String {
        match self.wire_fault {
            Some(fault) => fault.apply_to_body(body),
            None => body,
        }
    }

    #[cfg(not(feature = "test-util"))]
    fn faulted_body(&self, body: String) -> String {
        body
    }

    /// Builds both bodies and applies every pre-send limit.
    fn prepare_checked(&self, request: &JudgeRequest) -> Result<Prepared, JevError> {
        let prepared = self.prepare(request)?;
        validate::enforce_count_and_message_limits(
            self.provider.id.descriptor().request_limit_bytes(),
            &prepared.count_body,
            &prepared.message_body,
        )?;
        Ok(prepared)
    }

    fn validate_for_send(&self, request: &JudgeRequest) -> Result<(), JevError> {
        self.prepare_checked(request).map(|_| ())
    }

    fn judge(&self, request: &JudgeRequest, trace: &SendTrace) -> Result<JudgeOutcome, JevError> {
        let log = self.log.as_ref();
        GeneralEvent::debug(TARGET, "judge.start", "LLM judge started")
            .with_field("backend", self.provider.name)
            .with_field("model", self.provider.model.as_str())
            .emit(log);
        let result = self.judge_inner(request, trace);
        match &result {
            Ok(_) => GeneralEvent::debug(TARGET, "judge.done", "LLM judge answered")
                .with_field("backend", self.provider.name)
                .with_field("model", self.provider.model.as_str())
                .emit(log),
            Err(error) => GeneralEvent::warn(TARGET, "judge.failed", "LLM judge failed")
                .with_field("backend", self.provider.name)
                .with_field("model", self.provider.model.as_str())
                .with_error_code(error.code().as_str())
                .emit(log),
        }
        result
    }

    fn judge_inner(
        &self,
        request: &JudgeRequest,
        trace: &SendTrace,
    ) -> Result<JudgeOutcome, JevError> {
        let prepared = self.prepare_checked(request)?;
        // REQ-SAG-0606: the digest is recovered from the final serialized
        // message body before any request is handed to `send_with_busy_retry`.
        // A body that cannot be parsed fails here and nothing is sent.
        let input_sha256 = wire::recovered_digest(self.provider.kind, &prepared.message_body)?;
        let prompt_tokens = self.exchange(
            &self.provider.count_endpoint,
            &prepared.count_body,
            trace,
            |response| wire::parse_count(response.body()),
        )?;
        GeneralEvent::debug(TARGET, "judge.counted", "provider token count received")
            .with_field("backend", self.provider.name)
            .with_field("prompt_tokens", prompt_tokens)
            .emit(self.log.as_ref());
        validate::enforce_input_token_limit(prompt_tokens)?;
        let (reply, answers) = self.exchange(
            &self.provider.message_endpoint,
            &prepared.message_body,
            trace,
            |response| {
                let reply = wire::parse_vendor(self.provider.kind, response.body())?;
                if let Some(reason) = &reply.truncation {
                    return Err(JevError::response_invalid_because(
                        ResponseInvalidCause::Truncated,
                        reason.clone(),
                    ));
                }
                let answers =
                    v1::parse_output(self.provider.model.family(), &reply.text, request.payload())?;
                Ok((reply, answers))
            },
        )?;
        Ok(JudgeOutcome::new(self.provider.id, request, answers)?
            .with_provider_meta(wire::provider_meta(
                &reply,
                self.provider.model.as_str(),
                prompt_tokens,
            ))
            .with_input_sha256(input_sha256))
    }

    fn prepare(&self, request: &JudgeRequest) -> Result<Prepared, JevError> {
        let prompt = request
            .llm()
            .ok_or_else(|| JevError::input_invalid("LLM system prompt is required"))?;
        let payload_text = self.embedded_text(request.payload().as_str());
        validate::validate_questions(request.payload())?;
        let message_body: Arc<str> = Arc::from(self.faulted_body(wire::message_body(
            self.provider.kind,
            self.provider.model.as_str(),
            &payload_text,
            &prompt.system_prompt,
        )));
        let count_body: Arc<str> = Arc::from(wire::count_body(
            self.provider.kind,
            self.provider.model.as_str(),
            &payload_text,
            &prompt.system_prompt,
        ));
        Ok(Prepared {
            message_body,
            count_body,
        })
    }

    /// One provider call: busy retry, any status but 200 is an error, then
    /// `parse`. Every error is redacted inside `send_and_parse` and then
    /// labelled with the provider name.
    fn exchange<R>(
        &self,
        endpoint: &Endpoint,
        body: &Arc<str>,
        trace: &SendTrace,
        parse: impl FnOnce(HttpResponse) -> Result<R, JevError>,
    ) -> Result<R, JevError> {
        let request = self.http_request(endpoint, body);
        self.http
            .send_and_parse(&request, trace.clone(), |response| {
                if response.status() != 200 {
                    return Err(api_failure(
                        self.provider.name,
                        ReplyShape::Llm,
                        &request,
                        &response,
                    ));
                }
                parse(response)
            })
            .map_err(|error| error.prefix_detail(self.provider.name))
    }

    fn http_request(&self, endpoint: &Endpoint, body: &Arc<str>) -> HttpRequest {
        wire::unsigned_headers(self.provider.kind)
            .into_iter()
            .fold(
                HttpRequest::new(Method::Post, endpoint.clone(), Arc::clone(body)),
                |request, (name, value)| request.with_header(name, value),
            )
            .with_secret(wire::secret_header(
                self.provider.kind,
                self.api_key.clone(),
            ))
    }
}

/// Generates one public backend type over [`Client`].
///
/// Both public types keep their own names, constructors, and docs; their
/// behavior is the shared client plus a [`Provider`] descriptor.
macro_rules! llm_backend {
    (
        $(#[$meta:meta])*
        $name:ident, $provider:expr, header = $header:literal
    ) => {
        $(#[$meta])*
        #[derive(Clone)]
        pub struct $name<T = UreqTransport> {
            client: Client<T>,
        }

        impl $name<UreqTransport> {
            /// Creates the backend over [`UreqTransport`] with the default
            /// [`Timeouts`] (connect 10 s, request 120 s; ADR-SAG-0007).
            ///
            /// The backend registry calls only this constructor, so the
            /// transport type can change without touching `sc-jev-check`.
            #[must_use]
            pub fn with_default_transport(api_key: ResolvedApiKey) -> Self {
                Self::new(api_key, UreqTransport::new(Timeouts::default()))
            }
        }

        #[cfg(feature = "test-util")]
        impl $name<UreqTransport> {
            /// A backend for `http://127.0.0.1:<port>` over a real loopback
            /// HTTP transport, making at most `sends` sends per call
            /// (feature `test-util`).
            ///
            /// For the binary's loopback test seam only. Production builds
            /// have no such constructor.
            #[must_use]
            pub fn loopback(api_key: ResolvedApiKey, port: u16, sends: u32) -> Self {
                let mut backend = Self::new(
                    api_key,
                    UreqTransport::loopback_for_tests(Timeouts::default()),
                )
                .with_busy_policy(BusyPolicy::new(sends));
                let provider = &mut backend.client.provider;
                provider.message_endpoint = Endpoint::loopback_http(port, "/message");
                provider.count_endpoint = Endpoint::loopback_http(port, "/count");
                backend
            }
        }

        impl<T: Transport> $name<T> {
            #[doc = concat!("Builds a ", stringify!($name), " over `transport`.")]
            ///
            /// `api_key` is the resolved credential, already normalized by
            /// [`ResolvedApiKey::try_new`]. It travels only as a
            #[doc = concat!("`", $header, "` [`SecretHeader`](sc_agent_http::SecretHeader);")]
            /// this type does not read it (ADR-SAG-0020). To change the
            /// timeouts, pass `UreqTransport::new(Timeouts::new(..))`.
            ///
            /// Construction is infallible: key validation happens once, in
            /// [`ResolvedApiKey::try_new`] (ADR-SAG-0020 r-1 amendment).
            #[must_use]
            pub fn new(api_key: ResolvedApiKey, transport: T) -> Self {
                Self {
                    client: Client::new($provider, api_key, transport),
                }
            }

            /// Sets the model sent and reported (default: the catalog
            /// default of this backend, REQ-SAG-0148). A model string this
            /// build does not know is sent verbatim.
            #[must_use]
            pub fn with_model(mut self, model: ModelId) -> Self {
                self.client.provider.model = model;
                self
            }

            /// Replaces the busy-retry policy (default
            /// [`BusyPolicy::default`], REQ-SAG-0505).
            ///
            /// Tests pass `BusyPolicy::with_test_hooks` (feature
            /// `sc-agent-http/test-util`) so nothing sleeps.
            #[must_use]
            pub fn with_busy_policy(mut self, policy: BusyPolicy) -> Self {
                self.client.http = self.client.http.with_busy_policy(policy);
                self
            }

            /// Injects the general log: this backend's events and, through
            /// the HTTP layer, its busy-retry events. Unset, nothing is
            /// logged.
            #[must_use]
            pub fn with_general_log(mut self, log: SharedGeneralLog) -> Self {
                self.client.http = self.client.http.with_general_log(Arc::clone(&log));
                self.client.log = log;
                self
            }

            /// Sets the token that cancels a `judge` call between attempts
            /// and during busy waits. A cancel during an in-flight request is
            /// seen when it returns (worst case: the request timeout).
            #[must_use]
            pub fn with_cancel(mut self, cancel: CancelToken) -> Self {
                self.client.http = self.client.http.with_cancel(cancel);
                self
            }

            /// Seeds `fault` into the wire builder (feature `test-util`).
            ///
            /// The fault is applied after the canonical bytes are embedded
            /// and before the reported `input_sha256` is recovered from the
            /// message body (REQ-SAG-0606). Production builds leave the
            /// feature off.
            #[cfg(feature = "test-util")]
            #[must_use]
            pub fn with_wire_fault(mut self, fault: WireFault) -> Self {
                self.client.wire_fault = Some(fault);
                self
            }
        }

        impl<T> fmt::Debug for $name<T> {
            fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
                formatter
                    .debug_struct(stringify!($name))
                    .field("model", &self.client.provider.model.as_str())
                    .field("host", &self.client.provider.host)
                    .finish_non_exhaustive()
            }
        }

        impl<T: Transport> JudgeBackend for $name<T> {
            fn id(&self) -> BackendId {
                self.client.provider.id
            }

            fn validate_for_send(&self, request: &JudgeRequest) -> Result<(), JevError> {
                self.client.validate_for_send(request)
            }

            fn model_id(&self) -> ModelId {
                self.client.provider.model.clone()
            }

            /// Judges `request`: a token count, then the judge message.
            ///
            /// Worst case, each of the two exchanges takes a 90 s busy-retry
            /// budget plus a 120 s in-flight request (about 210 s), so one call
            /// can take about 420 s. See the module documentation.
            fn judge(
                &self,
                request: &JudgeRequest,
                trace: &SendTrace,
            ) -> Result<JudgeOutcome, JevError> {
                self.client.judge(request, trace)
            }
        }
    };
}

llm_backend! {
    /// API-direct Anthropic Haiku judge.
    ///
    /// # Examples
    ///
    /// ```
    /// use std::sync::Arc;
    ///
    /// use sc_agent_types::{BackendKeyId, JevError, NetworkErrorKind, ResolvedApiKey, SendTrace};
    /// use sc_decision_schema::{CanonicalJudgePayload, JudgeBackend, JudgeRequest, LlmWireContext, PayloadBundle};
    /// use sc_agent_http::{HttpRequest, HttpResponse, Transport};
    /// use sc_jev_backends::AnthropicHaikuBackend;
    ///
    /// struct Offline;
    ///
    /// impl Transport for Offline {
    ///     fn send(&self, _request: &HttpRequest) -> Result<HttpResponse, JevError> {
    ///         Err(JevError::network(NetworkErrorKind::Connect, "offline"))
    ///     }
    /// }
    ///
    /// let key = ResolvedApiKey::try_new(BackendKeyId::Anthropic, "test-key".to_owned())?;
    /// let backend = AnthropicHaikuBackend::new(key, Offline);
    /// let payload: CanonicalJudgePayload = serde_json::from_value(serde_json::json!({
    ///     "questions": [{"id": "q", "prompt": "Is it?", "choices": ["no", "yes"]}],
    ///     "state": []
    /// }))
    /// .expect("payload");
    /// let request = JudgeRequest::new(
    ///     Arc::new(PayloadBundle::encode(&payload)?),
    ///     Some(LlmWireContext::new("Judge.")),
    /// );
    /// backend.validate_for_send(&request)?;
    /// assert_eq!(
    ///     backend.judge(&request, &SendTrace::new()).unwrap_err().code(),
    ///     "NETWORK_ERROR"
    /// );
    /// # Ok::<(), JevError>(())
    /// ```
    AnthropicHaikuBackend, Provider::haiku(), header = "x-api-key"
}

