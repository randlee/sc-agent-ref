//! Haiku and Luna [`JudgeBackend`] implementations.
//!
//! Both backends validate byte and token limits, count tokens, then send the
//! judge message. `validate_for_send` applies those limits before any HTTP
//! call. The provider count is checked again before the judge message is
//! posted (ADR-SAG-0004). The count request uses the same body as the judge
//! call except Haiku omits `max_tokens`.
//!
//! # Worst-case wall time of one `judge` call
//!
//! A `judge` call is two exchanges (the token count, then the judge message).
//! Each exchange is bounded by the shared busy-retry budget of 90 s of waiting
//! plus one in-flight request of at most 120 s (the transport request
//! timeout), so one exchange is at most about 210 s and one `judge` call at
//! most about 420 s. A cancel token ends the wait between attempts within
//! 100 ms but not an in-flight request. There is no further deadline.
//!
//! The two public types are generated by one private macro over the shared
//! [`Client`], so they cannot drift apart. HTTP, busy retry, the response cap
//! and redaction are `sc-agent-http` (ADR-SAG-0026); this module builds the
//! provider requests and reads the replies.

